#!/usr/bin/env python3
"""Generate fluent setters from Swift compiler symbol graphs."""

import argparse
import copy
import json
import os
from pathlib import Path
import platform
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
EXPLICIT_CLASSES = json.loads((ROOT / "scripts/classes.json").read_text())
BUTTON_METHODS = {
    "title": "setTitle(_:for:)",
    "titleColor": "setTitleColor(_:for:)",
    "image": "setImage(_:for:)",
    "backgroundImage": "setBackgroundImage(_:for:)",
    "attributedTitle": "setAttributedTitle(_:for:)",
}
HEADER = "// Generated by scripts/generate.py from Swift Symbol Graph. Do not edit.\n"


def run(*args):
    return subprocess.check_output(args, text=True).strip()


def spelling(fragments):
    return "".join(f["spelling"] for f in fragments)


def version(value):
    return ".".join(str(value[k]) for k in ("major", "minor", "patch") if k in value)


def unavailable(symbol):
    return any(a.get("domain") in ("iOS", "Swift", "*") and
               (a.get("isUnconditionallyUnavailable") or a.get("obsoleted"))
               for a in symbol.get("availability", []))


def version_key(value):
    return tuple(value.get(k, 0) for k in ("major", "minor", "patch"))


def ios_introduced(symbol):
    return max((version_key(a["introduced"]) for a in symbol.get("availability", [])
                if a.get("domain") == "iOS" and "introduced" in a), default=(0, 0, 0))


def availability(symbol, minimum_ios=(0, 0, 0)):
    result = []
    merged = {}
    for original in symbol.get("availability", []):
        domain = original.get("domain")
        if domain not in ("iOS", "Swift", "*"):
            continue
        item = merged.setdefault(domain, {})
        for key, value in original.items():
            if key == "introduced" and key in item:
                value = max(item[key], value, key=version_key)
            elif key in ("deprecated", "obsoleted") and key in item:
                value = min(item[key], value, key=version_key)
            item[key] = value
    for item in merged.values():
        domain = item.get("domain")
        if domain not in ("iOS", "Swift", "*"):
            continue
        fields = [domain.lower() if domain == "Swift" else domain]
        for name in ("introduced", "deprecated", "obsoleted"):
            if name in item:
                value = item[name]
                if domain == "iOS" and name == "introduced" and version_key(value) < minimum_ios:
                    value = dict(zip(("major", "minor", "patch"), minimum_ios))
                fields.append(f"{name}: {version(value)}")
        if item.get("isUnconditionallyDeprecated"):
            fields.append("deprecated")
        if item.get("message"):
            fields.append("message: " + json.dumps(item["message"]))
        if len(fields) > 1:
            result.append("@available(" + ", ".join(fields) + ")")
    return result


def property_type(symbol):
    declaration = spelling(symbol["declarationFragments"])
    return declaration.split(": ", 1)[1].rsplit(" { ", 1)[0].replace("!", "?")


def writable(symbol):
    return any(fragment["spelling"] == "set" for fragment in symbol["declarationFragments"])


def load_symbols(directory):
    symbols, relations = {}, []
    for path in sorted(directory.glob("*.symbols.json")):
        graph = json.loads(path.read_text())
        for symbol in graph["symbols"]:
            symbol["module"] = graph["module"]["name"]
            symbols[symbol["identifier"]["precise"]] = symbol
        relations.extend(graph["relationships"])
    if not symbols:
        raise ValueError(f"No symbol graphs in {directory}")
    return symbols, relations


def class_symbols(symbols):
    return {s["pathComponents"][0]: s for s in symbols.values()
            if s["kind"]["identifier"] == "swift.class" and len(s["pathComponents"]) == 1}


def ancestors(identifier, parents):
    parent = parents.get(identifier)
    while parent:
        yield parent
        parent = parents.get(parent)


def select_classes(symbols, relations):
    classes = class_symbols(symbols)
    missing = sorted(set(EXPLICIT_CLASSES) - classes.keys())
    if missing:
        raise ValueError(f"Selected classes are missing: {missing}")
    selected = dict(EXPLICIT_CLASSES)
    parents = {r["source"]: r["target"] for r in relations if r["kind"] == "inheritsFrom"}
    roots = {classes[name]["identifier"]["precise"] for name in ("UIView", "UIViewController")}
    for name, symbol in classes.items():
        identifier = symbol["identifier"]["precise"]
        if symbol["module"] == "UIKit" and not unavailable(symbol) and (
                identifier in roots or any(parent in roots for parent in ancestors(identifier, parents))):
            selected[name] = symbol["module"]
    for name in list(selected):
        for parent in ancestors(classes[name]["identifier"]["precise"], parents):
            if parent == "c:objc(cs)NSObject":
                break
            symbol = symbols[parent]
            selected[symbol["pathComponents"][-1]] = symbol["module"]
    return dict(sorted(selected.items()))


def model(symbols, relations, selected):
    classes = class_symbols(symbols)
    parents = {r["source"]: r["target"] for r in relations if r["kind"] == "inheritsFrom"}
    members, requirements, conformances = {}, {}, {}
    for relation in relations:
        if relation["kind"] == "memberOf" and relation["source"] in symbols:
            symbol = symbols[relation["source"]]
            target = relation["target"]
            # UIKit adds accessibility properties to NSObject. Limit the fluent API to responders.
            if target == "c:objc(cs)NSObject" and symbol["module"] == "UIKit":
                target = classes["UIResponder"]["identifier"]["precise"]
            members.setdefault(target, {})[relation["source"]] = symbol
        elif relation["kind"] in ("requirementOf", "optionalRequirementOf") and relation["source"] in symbols:
            requirements.setdefault(relation["target"], {})[relation["source"]] = symbols[relation["source"]]
        elif relation["kind"] == "conformsTo":
            conformances.setdefault(relation["source"], set()).add(relation["target"])
    props, skipped, methods = {}, [], {}
    for name in selected:
        cls = classes[name]
        class_id = cls["identifier"]["precise"]
        own = {s["pathComponents"][-1]: s for s in members.get(class_id, {}).values()}
        declared = set(own)
        # Some UIKit properties are declared only in an adopted protocol.
        pending = sorted(conformances.get(class_id, []))
        visited = set()
        while pending:
            protocol = pending.pop()
            if protocol in visited:
                continue
            visited.add(protocol)
            pending.extend(sorted(conformances.get(protocol, [])))
            for requirement in requirements.get(protocol, {}).values():
                if requirement["kind"]["identifier"] != "swift.property":
                    continue
                inherited = copy.deepcopy(requirement)
                inherited["availability"] = inherited.get("availability", []) + symbols.get(protocol, {}).get("availability", [])
                title = inherited["pathComponents"][-1]
                previous = own.get(title)
                # A getter-only protocol does not remove another protocol's setter.
                if previous is None or (title not in declared and writable(inherited) and
                                        not unavailable(inherited) and not writable(previous) and
                                        property_type(previous) == property_type(inherited)):
                    own[title] = inherited
        props[name] = {}
        for member in own.values():
            kind = member["kind"]["identifier"]
            title = member["pathComponents"][-1]
            if kind == "swift.method":
                methods[(name, title)] = member
            if kind != "swift.property":
                continue
            reason = None
            if not writable(member):
                reason = "read-only"
            elif unavailable(cls) or unavailable(member):
                reason = "unavailable or obsoleted on iOS"
            if reason:
                skipped.append({"member": f"{name}.{title}", "reason": reason})
            else:
                props[name][title] = member
    # Keep writable overrides when their parent has no generated setter.
    for name, own in props.items():
        parent = parents.get(classes[name]["identifier"]["precise"])
        while parent:
            parent_symbol = symbols.get(parent)
            parent_name = parent_symbol["pathComponents"][-1] if parent_symbol else None
            for title in list(own):
                inherited = props.get(parent_name, {}).get(title)
                if inherited and property_type(inherited) == property_type(own[title]):
                    skipped.append({"member": f"{name}.{title}", "reason": f"inherited from {parent_name}"})
                    del own[title]
            parent = parents.get(parent)
    return classes, props, methods, skipped


def block(lines):
    return "\n".join(lines) + "\n"


def static_sources(classes, props, methods, selected):
    result = {}
    for name, module in selected.items():
        lines = [HEADER.rstrip(), f"import {module}", ""]
        if not unavailable(classes[name]):
            lines += availability(classes[name]) + [f"public extension {name} {{"]
            for title, symbol in sorted(props[name].items()):
                typ = property_type(symbol)
                # A non-optional closure passed to a stored property must escape.
                escaping = "@escaping " if "->" in typ and not typ.endswith("?") else ""
                lines += ["    " + a for a in availability(symbol, ios_introduced(classes[name]))]
                lines += ["    @discardableResult",
                          f"    func `{title}`(_ value: {escaping}{typ}) -> Self {{",
                          f"        self.{title} = value", "        return self", "    }", ""]
            if name == "UIButton":
                for alias, selector in BUTTON_METHODS.items():
                    symbol = methods[(name, selector)]
                    parameters = symbol["functionSignature"]["parameters"]
                    typ = spelling(parameters[0]["declarationFragments"]).split(": ", 1)[1].replace("!", "?")
                    state = spelling(parameters[1]["declarationFragments"]).split(": ", 1)[1]
                    native = selector.split("(")[0]
                    lines += ["    " + a for a in availability(symbol)]
                    lines += ["    @discardableResult",
                              f"    func {alias}(_ value: {typ}, for state: {state} = .normal) -> Self {{",
                              f"        {native}(value, for: state)", "        return self", "    }", ""]
            lines.append("}")
        result[f"{name}+Chainable.swift"] = block(lines)
    return result


def reactive_properties(classes, props, relations):
    parents = {r["source"]: r["target"] for r in relations if r["kind"] == "inheritsFrom"}
    names = {symbol["identifier"]["precise"]: name for name, symbol in classes.items()}
    root = classes["UIView"]["identifier"]["precise"]
    result = {name: dict(properties) for name, properties in props.items()
              if not unavailable(classes[name]) and (name == "UIView" or
                  root in ancestors(classes[name]["identifier"]["precise"], parents))}
    # Bindings belong to UIView; static methods above it remain on their SDK class.
    for parent in ancestors(root, parents):
        for title, symbol in props.get(names.get(parent), {}).items():
            result["UIView"].setdefault(title, symbol)
    return result


def reactive_sources(classes, props, methods, selected, framework):
    result = {}
    for name, properties in props.items():
        lines = [HEADER.rstrip(), f"import {selected[name]}", f"import {framework}", ""]
        minimum = max(ios_introduced(classes[name]), (13, 0, 0) if framework == "Combine" else (0, 0, 0))
        if framework == "Combine":
            lines.append("@available(iOS 13.0, *)")
        lines += availability(classes[name], minimum)
        lines.append(f"extension ViewConfigurable where Self: {name} {{")
        entries = [(title, symbol, property_type(symbol), False) for title, symbol in sorted(properties.items())]
        if name == "UIButton":
            for alias, selector in BUTTON_METHODS.items():
                symbol = methods[(name, selector)]
                typ = spelling(symbol["functionSignature"]["parameters"][0]["declarationFragments"]).split(": ", 1)[1].replace("!", "?")
                entries.append((alias, symbol, typ, True))
        for title, symbol, typ, is_method in entries:
            for value_type in ([typ[:-1], typ] if typ.endswith("?") else [typ]):
                lines += ["    " + a for a in availability(symbol, minimum)]
                lines.append("    @discardableResult")
                state = ", for state: UIControl.State = .normal" if is_method else ""
                if framework == "RxSwift":
                    lines.append(f"    public func `{title}`(_ source: Observable<{value_type}>{state}) -> Self {{")
                else:
                    lines += [f"    public func `{title}`<P: Publisher>(_ source: P{state}) -> Self",
                              f"        where P.Output == {value_type}, P.Failure == Never {{"]
                if is_method:
                    helper = "bindRx" if framework == "RxSwift" else "bindCombine"
                    native = BUTTON_METHODS[title].split("(")[0]
                    lines += [f'        {helper}(source, to: self, key: "button.{title}.\\(state.rawValue)") {{ view, value in',
                              f"            view.{native}(value, for: state)", "        }", "        return self"]
                elif "->" in typ:
                    # Swift 5 can import closure attributes differently in a key path's Value.
                    helper = "bindRx" if framework == "RxSwift" else "bindCombine"
                    lines += [f"        {helper}(source, to: self, key: \\Self.{title}) {{ view, value in",
                              f"            view.{title} = value", "        }", "        return self"]
                else:
                    lines.append(f"        return bind(source, to: \\.{title})")
                lines += ["    }", ""]
        lines.append("}")
        result[f"{name}+{'Rx' if framework == 'RxSwift' else 'Combine'}.swift"] = block(lines)
    return result


def write_files(directory, sources):
    directory.mkdir(parents=True, exist_ok=True)
    for name, content in sources.items():
        (directory / name).write_text(content)


def install(directory, sources, check):
    expected = set(sources)
    existing = {p.name for p in directory.glob("*") if p.is_file()} if directory.exists() else set()
    changed = sorted(name for name in expected | existing
                     if name not in expected or name not in existing or
                     (directory / name).read_text() != sources[name])
    if check:
        if changed:
            raise ValueError(f"Generated files differ in {directory}: {changed}")
        return
    directory.mkdir(parents=True, exist_ok=True)
    for name, content in sources.items():
        with tempfile.NamedTemporaryFile(mode="w", dir=directory, delete=False) as output:
            output.write(content)
        os.chmod(output.name, 0o644)
        os.replace(output.name, directory / name)
    for name in existing - expected:
        (directory / name).unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--symbols", type=Path, help="Reuse graphs extracted by this toolchain")
    parser.add_argument("--declarative-root", type=Path, help="Also generate Rx and Combine methods for UIView classes")
    parser.add_argument("--check", action="store_true", help="Compile and check without changing generated files")
    args = parser.parse_args()
    sdk = run("xcrun", "--sdk", "iphonesimulator", "--show-sdk-path")
    target = f"{platform.machine()}-apple-ios15.0-simulator"
    with tempfile.TemporaryDirectory(prefix="egchainable-") as temporary:
        work = Path(temporary)
        graphs = args.symbols or work / "symbols"
        if args.symbols is None:
            graphs.mkdir()
            for module in sorted(set(EXPLICIT_CLASSES.values())):
                print(f"Extracting {module}", flush=True)
                run("xcrun", "swift-symbolgraph-extract", "-module-name", module,
                    "-target", target, "-swift-version", "5", "-sdk", sdk,
                    "-module-cache-path", str(work / "modules"), "-output-dir", str(graphs),
                    "-minimum-access-level", "public", "-skip-synthesized-members")
        symbols, relations = load_symbols(graphs)
        selected = select_classes(symbols, relations)
        classes, props, methods, skipped = model(symbols, relations, selected)
        reactive = reactive_properties(classes, props, relations)
        sources = static_sources(classes, props, methods, selected)
        write_files(work / "Generated", sources)
        print(f"Checking {len(sources)} generated classes", flush=True)
        run("xcrun", "swiftc", "-typecheck", "-swift-version", "5", "-sdk", sdk,
            "-target", target, "-module-cache-path", str(work / "modules"),
            *[str(p) for p in sorted((work / "Generated").glob("*.swift"))],
            str(ROOT / "scripts/Client.swift"))
        report = {
            "toolchain": {"xcode": run("xcodebuild", "-version"), "swift": run("xcrun", "swiftc", "--version"),
                          "sdk": run("xcrun", "--sdk", "iphonesimulator", "--show-sdk-version"), "languageMode": "5"},
            "classes": selected,
            "discovery": {"roots": ["UIView", "UIViewController"], "module": "UIKit",
                          "ancestorStop": "NSObject", "explicitClasses": sorted(EXPLICIT_CLASSES)},
            "categoryProjection": {"module": "UIKit", "from": "NSObject", "to": "UIResponder"},
            "generatedProperties": {name: sorted(properties) for name, properties in props.items()},
            "reactiveProperties": {name: sorted(properties) for name, properties in reactive.items()},
            "methodAliases": BUTTON_METHODS,
            "excludedProperties": sorted(skipped, key=lambda entry: entry["member"]),
        }
        sources["manifest.json"] = json.dumps(report, indent=2, sort_keys=True) + "\n"
        outputs = [(ROOT / "EGChainable/Classes/Generated", sources)]
        if args.declarative_root:
            for directory, framework in (("Rx", "RxSwift"), ("Combine", "Combine")):
                outputs.append((args.declarative_root / "DeclarativeUIKit/Classes" / directory / "Generated",
                                reactive_sources(classes, reactive, methods, selected, framework)))
        # Check every output before any write in check mode.
        for directory, content in outputs:
            install(directory, content, args.check)
        print("Generated sources are current." if args.check else "Generated sources updated.")


if __name__ == "__main__":
    main()
